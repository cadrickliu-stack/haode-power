export type GeneratorSpecificationField =
  | "type"
  | "outputKw"
  | "outputKva"
  | "current"
  | "engineModel"
  | "cylinders"
  | "boreStroke"
  | "bore"
  | "stroke"
  | "fuelConsumption"
  | "oilCapacity"
  | "specificFuelConsumption"
  | "dimensions"
  | "weight";

export type GeneratorSpecificationColumn = {
  key: GeneratorSpecificationField;
  label: string;
  unit?: string;
};

export type GeneratorSpecification = Partial<Record<GeneratorSpecificationField, string>> & {
  type: string;
  engineModel: string;
  outputKw: string;
  outputKva: string;
};

export type GeneratorSeriesGroup = {
  name: string;
  columns: readonly GeneratorSpecificationColumn[];
  models: GeneratorSpecification[];
};

const column = (
  key: GeneratorSpecificationField,
  label: string,
  unit?: string,
): GeneratorSpecificationColumn => ({ key, label, unit });

const standardColumns = [
  column("type", "Type"),
  column("outputKw", "Output Power", "kW"),
  column("outputKva", "Output Power", "kVA"),
  column("current", "Current", "A"),
  column("engineModel", "Engine Model"),
  column("cylinders", "Cylinder"),
  column("boreStroke", "Bore × Stroke", "mm"),
  column("fuelConsumption", "FuelCon.", "L"),
  column("specificFuelConsumption", "Dis.", "g/kW.h"),
  column("dimensions", "Dimension", "mm L×W×H"),
  column("weight", "Weight", "kg"),
] as const;

const oilCapacityColumns = [
  ...standardColumns.slice(0, 8),
  column("oilCapacity", "Oil Capacity"),
  ...standardColumns.slice(8),
] as const;

const splitBoreStrokeColumns = [
  ...standardColumns.slice(0, 6),
  column("bore", "Bore", "mm"),
  column("stroke", "Stroke", "mm"),
  ...standardColumns.slice(7),
] as const;

function parseRows(
  columns: readonly GeneratorSpecificationColumn[],
  rawRows: string,
): GeneratorSpecification[] {
  return rawRows
    .trim()
    .split("\n")
    .map((rawRow, rowIndex) => {
      const values = rawRow.split("|").map((value) => value.trim());
      if (values.length !== columns.length) {
        throw new Error(
          `Generator specification row ${rowIndex + 1} has ${values.length} values; expected ${columns.length}.`,
        );
      }

      return Object.fromEntries(
        columns.map(({ key }, columnIndex) => [key, values[columnIndex]]),
      ) as GeneratorSpecification;
    });
}

function group(
  name: string,
  rawRows: string,
  columns: readonly GeneratorSpecificationColumn[] = standardColumns,
): GeneratorSeriesGroup {
  return { name, columns, models: parseRows(columns, rawRows) };
}

